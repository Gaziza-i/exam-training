class Command(BaseCommand):
    help = "Создаёт справочник предметов/тем ЕГЭ и небольшой набор демо-заданий"

    def handle(self, *args, **options):
        rus, _ = Subject.objects.get_or_create(
            code=Subject.RUSSIAN, defaults={"name": "Русский язык", "slug": "rus"}
        )
        math, _ = Subject.objects.get_or_create(
            code=Subject.MATH_BASE, defaults={"name": "Математика (база)", "slug": "math-base"}
        )

        self._seed_subject(rus, RUS_TOPICS, RUS_TASKS)
        self._seed_subject(math, MATH_BASE_TOPICS, MATH_TASKS)

        for subject_code, path in FIPI_BATCHES:
            if not path.exists():
                continue
            try:
                items = load_tasks_json(path)
                stats = import_tasks(subject_code, items)
            except FipiImportError as exc:
                self.stdout.write(self.style.WARNING(f"Пропущен {path.name}: {exc}"))
                continue
            self.stdout.write(
                f"{path.name}: заданий добавлено {stats.tasks_created}, "
                f"обновлено {stats.tasks_updated}, пропущено {stats.tasks_skipped}"
            )

        self.stdout.write(self.style.SUCCESS("Демо-данные готовы."))

    def _seed_subject(self, subject, topics, tasks_by_number):
        topics_created = 0
        tasks_created = 0
        for number, title in topics:
            topic, created = Topic.objects.get_or_create(
                subject=subject, task_number=number, defaults={"title": title}
            )
            if created:
                topics_created += 1
            for task_data in tasks_by_number.get(number, []):
                _, was_created = Task.objects.get_or_create(
                    topic=topic,
                    text=task_data["text"],
                    defaults={
                        "task_type": task_data.get("task_type", Task.TYPE_SHORT_ANSWER),
                        "options": task_data.get("options"),
                        "correct_answer": task_data["correct_answer"],
                        "explanation": task_data.get("explanation", ""),
                        "difficulty": task_data.get("difficulty", "base"),
                        "source": "seed",
                    },
                )
                if was_created:
                    tasks_created += 1
        self.stdout.write(f"{subject.name}: тем создано {topics_created}, заданий создано {tasks_created}")
